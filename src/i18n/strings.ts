export const STRINGS: Record<Lang, typeof en> = { en, ar };

/** Client-side lang detection (cookie set by the toggle). */
export function clientLang(): Lang {
  if (typeof document === "undefined") return "en";
  const m = document.cookie.split(";").map((c) => c.trim()).find((c) => c.startsWith("lang="));
  return m && m.split("=")[1] === "ar" ? "ar" : "en";
}

/** Pick the right version of a DB field. */
export function pick(arVal: string | null | undefined, enVal: string | null | undefined, ar: boolean): string | null | undefined {
  return ar ? (arVal || enVal) : enVal;
}

